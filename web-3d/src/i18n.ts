const DICTS: Record<Lang, Dict> = { en, ro };

/**
 * Language follows the device (its first preferred language: Romanian → ro, anything else → en), also live when the
 * device language changes. The EN/RO button sets an override that is remembered; choosing the device's language again
 * removes it.
 */
const systemLang = (): Lang => ((navigator.languages?.[0] || navigator.language || '').toLowerCase().startsWith('ro') ? 'ro' : 'en');
function savedLangOverride(): Lang | null {
  try { localStorage.removeItem('lang'); } catch { /* replaced by langOverride */ }
  const v = getPref('langOverride');
  return v === 'en' || v === 'ro' ? v : null;
}

let override: Lang | null = savedLangOverride();
let lang: Lang = override ?? systemLang();
const listeners = new Set<() => void>();
document.documentElement.lang = lang;

const apply = () => {
  lang = override ?? systemLang();
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
};
window.addEventListener('languagechange', apply);

export function setLang(next: Lang) {
  override = next === systemLang() ? null : next;
  setPref('langOverride', override);
  apply();
}
const subscribe = (l: () => void) => { listeners.add(l); return () => { listeners.delete(l); }; };

/** Current language (re-renders when it changes). */
export const useLang = () => useSyncExternalStore(subscribe, () => lang);
/** Texts in the current language. */
export const useT = () => DICTS[useLang()];
export const dictFor = (l: Lang) => DICTS[l];
